import "dotenv/config";
import { writeFileSync, mkdirSync } from "node:fs";
import { BridgeSource, PasswordSession, TelevendClient, readTelevendConfig } from "../../packages/televend/src/index.js";
import { cashCollectionsDay, eventsDay, refillsDay, salesDay, machinesSummary } from "../../packages/mcp-televend/src/tools.js";
const day = process.argv[2] ?? "2026-10-14";
const cfg = readTelevendConfig()!;
const s = new PasswordSession({ username: cfg.username!, password: cfg.password! }, { fetch: globalThis.fetch as never, now: Date.now });
const c = new TelevendClient(s, { tenantId: cfg.tenantId, companyId: cfg.companyId, minIntervalMs: 1000 });
const src = new BridgeSource(c, { tenantId: cfg.tenantId, companyId: cfg.companyId });
const machines = machinesSummary(await src.machines(), { enabledOnly: true, limit: 50 });
const sales = await salesDay(src, day);
const alarms = await eventsDay(src, day, { level: "alarm", limit: 50 });
const warnings = await eventsDay(src, day, { level: "warning", limit: 20 });
const cash = await cashCollectionsDay(src, day);
const refills = await refillsDay(src, day, { names: "initials", limit: 50 });
const out = { day, machines: { total: machines.totalMachines, enabled: machines.enabledMachines }, sales, alarms, warnings, cash, refills, requests: c.sent, signIns: s.passwordSignIns };
mkdirSync("private-data/reports", { recursive: true });
writeFileSync(`private-data/reports/snapshot-${day}.json`, JSON.stringify(out, null, 2));
console.log("done", day, "requests", c.sent);
